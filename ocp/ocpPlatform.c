static char id[32] = {0};
static char idsize = 0;
//===========================================================================

//===========================================================================
/*------------------------------- Functions -------------------------------*/
//===========================================================================
//---------------------------------------------------------------------------
int32_t ocpPlatformID(char *buffer, uint32_t maxsize){

	uint32_t k;
	char *p;

	if( maxsize < idsize ) return -1;

	k = idsize;
	p = id;
	while(k--) *buffer++ = *p++;

	return idsize;
}
//---------------------------------------------------------------------------
int32_t ocpPlatformSetID(char *buffer, uint32_t size){

	char *p;

	if( size > sizeof(id) ) return -1;

	idsize = size;
	p = id;
	while(size--) *p++ = *buffer++;

	return 0;
}
