void mcp49x2Write(mcp49x2_t *mcp, uint16_t data, uint16_t flags){

	uint16_t dataWrite;

	dataWrite = (data << mcp->res) | flags;

	mcp->csClear();
	mcp->spiWrite((uint8_t *)(&dataWrite), 2);
	mcp->csSet();
}
//-----------------------------------------------------------------------------
void mcp49x2CsWrite(mcp49x2_t *mcp, uint32_t cs){

	if( cs ) mcp->csSet();
	else mcp->csClear();
}
//-----------------------------------------------------------------------------
void mcp49x2LdacWrite(mcp49x2_t *mcp, uint32_t ldac){

	if( ldac && mcp->ldacSet ) mcp->ldacSet();
	else if ( (ldac == 0) && mcp->ldacClear ) mcp->ldacClear();
}
//-----------------------------------------------------------------------------
void mcp49x2ShdnWrite(mcp49x2_t *mcp, uint32_t shdn){

	if( shdn && mcp->shdnSet ) mcp->shdnSet();
	else if ( (shdn == 0) && mcp->shdnClear ) mcp->shdnClear();
}
